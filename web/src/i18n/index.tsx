const DICTS: Record<Lang, Partial<Record<Key, string>>> = {en, zh};

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key) => string;
}

const Ctx = createContext<I18nCtx>({lang: 'en', setLang: () => {}, t: k => en[k] ?? k});

const KEY = 'cb_web_lang';

function initialLang(): Lang {
  const stored = localStorage.getItem(KEY);
  if (stored === 'en' || stored === 'zh') return stored;
  return (navigator.language || 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function LanguageProvider({children}: {children: React.ReactNode}) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  const t = useCallback(
    (key: Key): string => DICTS[lang][key] ?? en[key] ?? key,
    [lang],
  );

  const value = useMemo<I18nCtx>(
    () => ({
      lang,
      setLang: l => {
        localStorage.setItem(KEY, l);
        setLangState(l);
        document.documentElement.setAttribute('lang', l === 'zh' ? 'zh-Hans' : 'en');
      },
      t,
    }),
    [lang, t],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
export type {Key as TKey};

